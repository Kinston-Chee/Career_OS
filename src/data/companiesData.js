// ─── Helpers ─────────────────────────────────────────────────────────────
export function getCompanyById(id) {
  return COMPANY_DIRECTORY.find((c) => c.id === id) || null
}

export function getCompanyOpenings(companyId) {
  return OPENINGS_BY_COMPANY[companyId] || []
}

// Returns { list, sameUniCount, total } — filtered so the caller can
// display "N peers from your university" and highlight them.
export function getCompanyPeers(companyId, userUniversity) {
  const list = PEERS_BY_COMPANY[companyId] || []
  const sameUniCount = userUniversity
    ? list.filter((p) => p.university === userUniversity).length
    : 0
  return { list, sameUniCount, total: list.length }
}
