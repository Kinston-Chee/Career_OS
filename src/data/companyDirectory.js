export const ALIGNMENT_LEVELS = LEVELS

// Grades a gap-alignment percentage the same way the reference design does.
function level(pct) {
  if (pct >= 85) return 'strong'
  if (pct >= 65) return 'good'
  if (pct >= 40) return 'partial'
  return 'weak'
}

function align(pairs) {
  return pairs.map(([name, pct]) => ({ name, pct, level: level(pct) }))
}

