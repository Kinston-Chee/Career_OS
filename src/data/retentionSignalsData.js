// ─── Derived headline metrics ─────────────────────────────────────────────
export const RETENTION_KPIS = () => {
  const atRisk = RETENTION_WATCHLIST.filter((e) => e.riskScore >= 60).length
  const critical = RETENTION_WATCHLIST.filter((e) => e.riskBand === 'critical').length
  const signalsFiring = RETENTION_SIGNALS.reduce((sum, s) => sum + s.flagged, 0)
  const avgCoverage = Math.round(
    RETENTION_SIGNALS.reduce((sum, s) => sum + s.coverage, 0) / RETENTION_SIGNALS.length,
  )
  return { atRisk, critical, signalsFiring, avgCoverage }
}
